<#
.SYNOPSIS
  DSH × Lark 机器人 —— Windows 一键安装脚本

.DESCRIPTION
  自动完成：环境检查 → 安装 DSH / lark-cli → 生成 config.json →
  注册开机自启（隐藏窗口 + 崩溃自动重启）→ 打印后续人工步骤。

.PARAMETER SkipDeps
  跳过 npm 全局安装（已装过 DSH / lark-cli 时用）

.PARAMETER Force
  重建 config.json（已有字段保留）

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\install-windows.ps1
#>
[CmdletBinding()]
param(
    [switch]$SkipDeps,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$Dir = Split-Path -Parent $MyInvocation.MyCommand.Path
$BotJs = Join-Path $Dir 'bot.mjs'
$TaskName = 'DSH-Lark-Bot'
$VbsFile = Join-Path $Dir 'run-hidden.vbs'

function Step($n, $msg) { Write-Host "`n[$n] $msg" -ForegroundColor Cyan }
function Ok($msg)   { Write-Host "  [OK] $msg" -ForegroundColor Green }
function Warn($msg) { Write-Host "  [!!] $msg" -ForegroundColor Yellow }
function Die($msg)  { Write-Host "  [XX] $msg" -ForegroundColor Red; exit 1 }

Write-Host @'
==========================================
  DSH × Lark 机器人 · Windows 安装
==========================================
'@ -ForegroundColor Magenta

# ── 1. Node.js ────────────────────────────────────────────────
Step 1 '检查 Node.js'
$nodeCmd = Get-Command node -ErrorAction SilentlyContinue
if (-not $nodeCmd) {
    Die '未找到 Node.js。请先安装 Node.js 20+：https://nodejs.org/zh-cn （或 winget install OpenJS.NodeJS.LTS），装完重开 PowerShell 再跑本脚本'
}
$nodeExe = $nodeCmd.Source
$nodeVersion = (& node -v).Trim()
$nodeMajor = [int]($nodeVersion.TrimStart('v').Split('.')[0])
if ($nodeMajor -lt 20) { Die "Node.js 版本过低：$nodeVersion（需要 20+，请升级）" }
Ok "Node.js $nodeVersion  → $nodeExe"

# ── 2. npm ────────────────────────────────────────────────────
Step 2 '检查 npm'
if (-not (Get-Command npm -ErrorAction SilentlyContinue)) { Die '未找到 npm（一般随 Node.js 安装，请重装 Node.js）' }
Ok "npm $((& npm -v).Trim())"

# ── 3. 依赖 ───────────────────────────────────────────────────
Step 3 '安装依赖：@deepseek-ai/dsh 与 @larksuite/cli'
if ($SkipDeps) {
    Warn '已指定 -SkipDeps，跳过 npm 安装'
} else {
    Write-Host '  npm i -g @deepseek-ai/dsh @larksuite/cli  （首次可能几分钟）' -ForegroundColor DarkGray
    & npm i -g '@deepseek-ai/dsh' '@larksuite/cli'
    if ($LASTEXITCODE -ne 0) {
        Die 'npm 安装失败。常见原因：网络（可先 npm config set registry https://registry.npmmirror.com）、权限（用管理员 PowerShell）'
    }
}
foreach ($cmdName in @('dsh', 'lark-cli')) {
    if (-not (Get-Command $cmdName -ErrorAction SilentlyContinue)) { Die "安装后仍找不到 $cmdName，请检查 npm 全局 bin 是否在 PATH" }
}
Ok "dsh / lark-cli 已就绪"

# ── 4. 生成 config.json ──────────────────────────────────────
Step 4 '生成 config.json（自动探测 DSH / lark-cli 绝对路径）'
# 始终 --force：从别的电脑拷来的 config.json 里是旧路径，必须按本机重新探测（owner/allowedUsers 会保留）
& node $BotJs --init --force
if ($LASTEXITCODE -ne 0) { Die 'config.json 生成失败' }

# ── 5. 注册开机自启 ──────────────────────────────────────────
Step 5 '注册开机自启（隐藏窗口 + 崩溃自动重启）'

# 注意：VBS 里引号用 Chr(34) 拼，避免多层转义；文件用系统 ANSI 编码写，WScript 才认
$vbs = @"
' Auto-generated by install-windows.ps1: run bot hidden, restart 5s after exit
Dim sh, q, cmd
Set sh = CreateObject("WScript.Shell")
sh.CurrentDirectory = "$Dir"
q = Chr(34)
Do
  cmd = q & "$nodeExe" & q & " " & q & "$BotJs" & q
  sh.Run cmd, 0, True
  WScript.Sleep 5000
Loop
"@
[System.IO.File]::WriteAllText($VbsFile, $vbs, [System.Text.Encoding]::Default)
Ok "看门狗脚本：$VbsFile"

$registered = $false
try {
    $wscript = Join-Path $env:SystemRoot 'System32\wscript.exe'
    $action = New-ScheduledTaskAction -Execute $wscript -Argument ('"' + $VbsFile + '"')
    $trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
    $settings = New-ScheduledTaskSettingsSet `
        -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
        -ExecutionTimeLimit ([TimeSpan]::Zero) `
        -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) `
        -MultipleInstances IgnoreNew
    Register-ScheduledTask -TaskName $TaskName `
        -Action $action -Trigger $trigger -Settings $settings `
        -Description 'DSH × Lark 机器人：Lark 消息 → DeepSeek Harness' -Force | Out-Null
    Start-ScheduledTask -TaskName $TaskName
    Start-Sleep -Seconds 2
    $registered = $true
    Ok "计划任务已注册并启动：$TaskName（登录时自动运行）"
} catch {
    Warn "计划任务注册失败：$($_.Exception.Message)"
    Warn '改用「启动文件夹」方式兜底'
    $startup = [Environment]::GetFolderPath('Startup')
    Copy-Item $VbsFile (Join-Path $startup 'DSH-Lark-Bot.vbs') -Force
    Start-Process (Join-Path $env:SystemRoot 'System32\wscript.exe') -ArgumentList ('"' + $VbsFile + '"')
    Ok "已放入启动文件夹：$startup\DSH-Lark-Bot.vbs（已立即启动）"
}

# ── 6. 收尾 ─────────────────────────────────────────────────
Start-Sleep -Seconds 2
$proc = Get-CimInstance Win32_Process -Filter "Name='node.exe'" -ErrorAction SilentlyContinue |
        Where-Object { $_.CommandLine -like '*bot.mjs*' }
if ($proc) { Ok "机器人进程已运行（PID $($proc.ProcessId -join ', ')）" }
else { Warn '未检测到 bot.mjs 进程，请稍后用 .\botctl.ps1 status 检查日志' }

Write-Host @'

==========================================
  代码侧安装完成 ✅
==========================================

接下来还有 3 件「需要你本人操作」的事（详细步骤见本套件文档
docs/FEISHU-SETUP.md；本脚本为上游 Windows 路径，未在本套件验证）：

  1. 绑定 Lark 应用（会弹网页/二维码）
       lark-cli config init --new
     → 打开输出的 verification_url，在浏览器里创建/绑定应用
     → 国内飞书加：--brand feishu（国际版用 --brand lark）

  2. 开发者后台核对 3 项（若上一步已自动完成则跳过）
       https://open.feishu.cn/app   （国内飞书；国际版是 open.larksuite.com）
       · 添加应用能力 → 机器人
       · 事件与回调 → 订阅方式 → 长连接 → 添加事件「接收消息 im.message.receive_v1」
       · 权限管理 → 开通 im:message / im:message:send_as_bot
       · 版本管理与发布 → 创建版本并发布 → 可用范围加上自己

  3. 填白名单 + 自检
       · 在 Lark 里给机器人发一句话，它会回复你的 open_id
       · 把 open_id 填进 config.json 的 ownerOpenId / allowedUsers
       · 然后把 chat_id 填进 testChatId
       · 运行：.\botctl.ps1 doctor    → 全绿即成功
       · 运行：.\botctl.ps1 test "你好"

管理命令：
  .\botctl.ps1 status | logs | restart | stop | start | doctor | test "文本" | uninstall

'@ -ForegroundColor Yellow
